"""
pages.py — Page Object Model for Oral Ulcer AI Web Application
All selectors use ARIA labels generated by Flutter Web's semantic tree.
"""
import time
from selenium.webdriver.common.by import By
from selenium.webdriver.support.ui import WebDriverWait
from selenium.webdriver.support import expected_conditions as EC
from selenium.common.exceptions import TimeoutException, NoSuchElementException
from selenium.webdriver.common.keys import Keys
from selenium.webdriver.common.action_chains import ActionChains


# ─────────────────────────────────────────────────────────────────
#  BASE PAGE — shared helpers
# ─────────────────────────────────────────────────────────────────
class BasePage:
    def __init__(self, driver):
        self.driver = driver

    def _process_xpath(self, xpath):
        import re
        if not xpath:
            return xpath
        # Convert contains(@aria-label, "foo") to (contains(@aria-label, "foo") or contains(., "foo"))
        pattern = r'contains\(@aria-label,\s*([\'"])([^\'"]+)\1\)'
        def replace(match):
            quote = match.group(1)
            text = match.group(2)
            return f'(contains(@aria-label, {quote}{text}{quote}) or contains(., {quote}{text}{quote}))'
        new_xpath = re.sub(pattern, replace, xpath)
        
        # Convert @aria-label="foo" to (@aria-label="foo" or .="foo")
        pattern_eq = r'@aria-label\s*=\s*([\'"])([^\'"]+)\1'
        def replace_eq(match):
            quote = match.group(1)
            text = match.group(2)
            return f'(@aria-label={quote}{text}{quote} or .={quote}{text}{quote})'
        new_xpath = re.sub(pattern_eq, replace_eq, new_xpath)

        # Convert contains(@role, "textbox") to (contains(@role, "textbox") or self::input)
        new_xpath = new_xpath.replace('contains(@role,"textbox")', '(contains(@role,"textbox") or self::input)')
        new_xpath = new_xpath.replace("contains(@role,'textbox')", "(contains(@role,'textbox') or self::input)")
        return new_xpath

    def wait_for_element(self, xpath, timeout=8):
        """Waits for element to be visible and returns it, else None."""
        xpath = self._process_xpath(xpath)
        try:
            return WebDriverWait(self.driver, timeout).until(
                EC.visibility_of_element_located((By.XPATH, xpath))
            )
        except TimeoutException:
            return None

    def wait_for_clickable(self, xpath, timeout=8):
        """Waits for element to be clickable and returns it, else None."""
        xpath = self._process_xpath(xpath)
        try:
            return WebDriverWait(self.driver, timeout).until(
                EC.element_to_be_clickable((By.XPATH, xpath))
            )
        except TimeoutException:
            return None

    def find_element(self, xpath):
        """Finds element without wait; returns None on failure."""
        xpath = self._process_xpath(xpath)
        try:
            return self.driver.find_element(By.XPATH, xpath)
        except Exception:
            return None

    def find_elements(self, xpath):
        """Finds all matching elements; returns empty list on failure."""
        xpath = self._process_xpath(xpath)
        try:
            return self.driver.find_elements(By.XPATH, xpath)
        except Exception:
            return []

    def wait_for_element_with_scroll(self, xpath, timeout=8):
        """Finds an element, scrolling down if not immediately present in DOM.
        Hard cap: will never block longer than 30s total to prevent session timeouts.
        """
        processed_xpath = self._process_xpath(xpath)
        print(f"[DEBUG] Searching for locator: {processed_xpath} (timeout={timeout}s) | Current URL: {self.driver.current_url}")
        start_time = time.time()
        MAX_TOTAL_WAIT = 30  # hard cap in seconds

        try:
            el = WebDriverWait(self.driver, 2).until(
                EC.presence_of_element_located((By.XPATH, processed_xpath))
            )
            self.driver.execute_script("arguments[0].scrollIntoView({block: 'center'});", el)
            time.sleep(0.3)
            print(f"[DEBUG] Found locator immediately: {processed_xpath}")
            return el
        except Exception as e:
            print(f"[DEBUG] Immediate search exception type: {type(e).__name__} for {processed_xpath}")
            pass

        for i in range(10):
            if time.time() - start_time > MAX_TOTAL_WAIT:
                print(f"[DEBUG] Total timeout exceeded ({MAX_TOTAL_WAIT}s) at scroll {i+1}, giving up")
                break
            try:
                el = WebDriverWait(self.driver, 1.0).until(
                    EC.presence_of_element_located((By.XPATH, processed_xpath))
                )
                self.driver.execute_script("arguments[0].scrollIntoView({block: 'center'});", el)
                time.sleep(0.3)
                print(f"[DEBUG] Found locator after scroll {i+1}: {processed_xpath}")
                return el
            except Exception as e:
                print(f"[DEBUG] Scroll {i+1} exception type: {type(e).__name__} for {processed_xpath}")
                try:
                    self.driver.execute_script("document.body.focus();")
                    self.driver.find_element(By.TAG_NAME, 'body').send_keys(Keys.PAGE_DOWN)
                except Exception:
                    pass
                try:
                    self.driver.execute_script("""
                        const el = document.querySelector('flutter-view') || document.body;
                        el.dispatchEvent(new WheelEvent('wheel', { deltaY: 500, bubbles: true }));
                    """)
                except Exception:
                    self.driver.execute_script("window.scrollBy(0, 500);")
                time.sleep(0.5)

        try:
            el = WebDriverWait(self.driver, 2).until(
                EC.presence_of_element_located((By.XPATH, processed_xpath))
            )
            print(f"[DEBUG] Found locator in final attempt: {processed_xpath}")
            return el
        except Exception as e:
            print(f"[DEBUG] Final search exception type: {type(e).__name__} for {processed_xpath} | NOT FOUND")
            return None

    def click_element(self, xpath, timeout=8):
        """Clicks element after waiting. Returns True on success."""
        from selenium.common.exceptions import StaleElementReferenceException
        import time

        processed_xpath = self._process_xpath(xpath)
        for attempt in range(2):
            if attempt == 0:
                element = self.wait_for_element_with_scroll(xpath, timeout)
            else:
                element = self.wait_for_element_with_scroll(xpath, timeout=3)
            if not element:
                if attempt == 0:
                    time.sleep(0.5)
                    continue
                print(f"[DEBUG] Click failed: locator {processed_xpath} NOT FOUND")
                return False

            try:
                # Primary: Standard click
                element.click()
                print(f"[DEBUG] Clicked locator via standard click: {processed_xpath}")
                return True
            except StaleElementReferenceException:
                print(f"[DEBUG] StaleElementReferenceException on standard click, retrying... (attempt {attempt+1})")
                time.sleep(0.5)
                continue
            except Exception as e1:
                print(f"[DEBUG] Standard click failed with exception: {type(e1).__name__} for {processed_xpath}")
                # Fallback 1: ActionChains click
                try:
                    from selenium.webdriver.common.action_chains import ActionChains
                    ActionChains(self.driver).move_to_element(element).click().perform()
                    print(f"[DEBUG] Clicked locator via ActionChains: {processed_xpath}")
                    return True
                except StaleElementReferenceException:
                    print(f"[DEBUG] StaleElementReferenceException on ActionChains click, retrying... (attempt {attempt+1})")
                    time.sleep(0.5)
                    continue
                except Exception as e2:
                    print(f"[DEBUG] ActionChains click failed with exception: {type(e2).__name__} for {processed_xpath}")
                    # Fallback 2: JS click (final fallback)
                    try:
                        self.driver.execute_script("arguments[0].click();", element)
                        print(f"[DEBUG] Clicked locator via JS click: {processed_xpath}")
                        return True
                    except StaleElementReferenceException:
                        print(f"[DEBUG] StaleElementReferenceException on JS click, retrying... (attempt {attempt+1})")
                        time.sleep(0.5)
                        continue
                    except Exception as e3:
                        print(f"[DEBUG] JS click failed with exception: {type(e3).__name__} for {processed_xpath}")
                        return False
        return False


    def input_text(self, xpath, text, timeout=8):
        """Clears field and types text. Returns True on success."""
        element = self.wait_for_element_with_scroll(xpath, timeout)
        processed_xpath = self._process_xpath(xpath)
        if element:
            try:
                element.clear()
                element.send_keys(text)
                print(f"[DEBUG] Inputted text '{text}' into locator: {processed_xpath}")
                return True
            except Exception as e:
                print(f"[DEBUG] Input text failed with exception: {type(e).__name__} for {processed_xpath}")
                return False
        else:
            print(f"[DEBUG] Input text failed: locator {processed_xpath} NOT FOUND")
        return False

    def element_exists(self, xpath, timeout=3):
        """Returns True if element is present in DOM within timeout."""
        processed_xpath = self._process_xpath(xpath)
        print(f"[DEBUG] Checking existence of locator: {processed_xpath} (timeout={timeout}s) | Current URL: {self.driver.current_url}")
        try:
            WebDriverWait(self.driver, timeout).until(
                EC.presence_of_element_located((By.XPATH, processed_xpath))
            )
            print(f"[DEBUG] Locator exists: {processed_xpath}")
            return True
        except TimeoutException as e:
            print(f"[DEBUG] Locator does NOT exist: {processed_xpath} (TimeoutException)")
            return False

    def get_element_text(self, xpath, timeout=5):
        """Returns the text content of an element, or empty string."""
        element = self.wait_for_element(xpath, timeout)
        if element:
            return element.text
        return ""

    def inject_print_mock(self):
        """Suppresses browser print dialog so PDF tests don't block execution."""
        script = """
            window.print = function() {
                console.log('Mocked window.print() called — test suite bypass.');
            };
            const _orig = document.createElement.bind(document);
            document.createElement = function(tag) {
                const el = _orig(tag);
                if (tag && tag.toLowerCase() === 'iframe') {
                    Object.defineProperty(el, 'contentWindow', {
                        get: function() {
                            const desc = Object.getOwnPropertyDescriptor(HTMLIFrameElement.prototype, 'contentWindow');
                            const win = desc.get.call(this);
                            if (win && !win.__printMocked__) {
                                win.__printMocked__ = true;
                                win.print = function() {
                                    console.log('Mocked iframe.contentWindow.print() called.');
                                };
                            }
                            return win;
                        }, configurable: true
                    });
                }
                return el;
            };
        """
        try:
            self.driver.execute_script(script)
            return True
        except Exception:
            return False

    def page_loaded(self, keyword, timeout=10):
        """Checks if a keyword appears anywhere in the page DOM (including Shadow DOM)."""
        print(f"[DEBUG] Checking page load with keyword: '{keyword}' (timeout={timeout}s) | Current URL: {self.driver.current_url}")
        script = """
            function findText(root, text) {
                if (!root) return false;
                const content = (root.innerText || root.textContent || '').toLowerCase();
                if (content.includes(text.toLowerCase())) return true;
                
                const children = root.children || [];
                for (let i = 0; i < children.length; i++) {
                    if (findText(children[i], text)) return true;
                }
                if (root.shadowRoot) {
                    if (findText(root.shadowRoot, text)) return true;
                }
                return false;
            }
            return findText(document.body, arguments[0]) || document.title.toLowerCase().includes(arguments[0].toLowerCase());
        """
        start_time = time.time()
        while time.time() - start_time < timeout:
            try:
                if self.driver.execute_script(script, keyword):
                    print(f"[DEBUG] Page loaded successfully with keyword '{keyword}' | result = True")
                    return True
            except Exception as e:
                print(f"[DEBUG] page_loaded JS search exception: {type(e).__name__}")
                pass
            time.sleep(0.5)
        print(f"[DEBUG] Page load FAILED with keyword '{keyword}' | result = False")
        return False



