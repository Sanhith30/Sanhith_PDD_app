class LoginPage(BasePage):
    # Toggle / mode switch
    SIGNUP_TOGGLE   = '//*[contains(@role,"button") and (contains(@aria-label,"Sign up") or contains(@aria-label,"Register"))]'

    # Sign-In fields
    EMAIL_INPUT     = '//input[contains(@aria-label, "clinician") or contains(@aria-label, "saveetha") or contains(@aria-label, "Email")] | //input[@type="email"] | (//input)[1]'
    PASSWORD_INPUT  = '(//input[@type="password"])[1]'
    SIGNIN_BTN      = '//*[contains(@role,"button") and contains(., "Sign In")]'

    # Sign-Up extra fields
    NAME_INPUT      = '//input[contains(@aria-label, "Smith") or contains(@aria-label, "Dr.") or contains(@aria-label, "Name")]'
    CONFIRM_PW_INPUT= '(//input[@type="password"])[2]'
    CREATE_BTN      = '//*[contains(@role,"button") and contains(., "Create Account")]'

    # Navigation
    FORGOT_LINK     = '//*[contains(@aria-label,"Forgot") or contains(@aria-label,"forgot")]'
    EYE_TOGGLE      = '//*[contains(@role,"button") and not(normalize-space(.)) and not(@aria-label)]'

    def login(self, email, password):
        self.input_text(self.EMAIL_INPUT, email)
        self.input_text(self.PASSWORD_INPUT, password)
        return self.click_element(self.SIGNIN_BTN)

    def switch_to_signup_mode(self):
        return self.click_element(self.SIGNUP_TOGGLE)

    def register(self, name, email, password, confirm=""):
        self.input_text(self.NAME_INPUT, name)
        self.input_text(self.EMAIL_INPUT, email)
        self.input_text(self.PASSWORD_INPUT, password)
        if confirm:
            self.input_text(self.CONFIRM_PW_INPUT, confirm)
        return self.click_element(self.CREATE_BTN)

    def click_forgot_password(self):
        return self.click_element(self.FORGOT_LINK)

    def toggle_password_visibility(self):
        return self.click_element(self.EYE_TOGGLE)

    def snackbar_exists(self, timeout=5):
        return self.element_exists('//*[contains(@role,"alert")] | //*[contains(@aria-label,"error") or contains(@aria-label,"incorrect")]', timeout)


